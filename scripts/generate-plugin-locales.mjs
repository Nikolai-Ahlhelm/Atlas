const localeFiles = readdirSync(LOCALES_DIR).filter((name) => name.endsWith('.json')).sort();
const locales = Object.fromEntries(localeFiles.map((file) => {
  const parsed = JSON.parse(readFileSync(join(LOCALES_DIR, file), 'utf8'));
  const code = String(parsed.code || file.replace(/\.json$/i, '')).toLowerCase();
  return [code, parsed];
}));

const english = locales.en || { ui: {} };

for (const [pluginKey, config] of Object.entries(pluginConfigs)) {
  const targetDir = join(PLUGINS_DIR, pluginKey, 'locales');
  mkdirSync(targetDir, { recursive: true });

  for (const file of localeFiles) {
    const code = file.replace(/\.json$/i, '').toLowerCase();
    const source = locales[code] || { ui: {} };
    const overrides = localeOverrides[code]?.[pluginKey] || {};
    const ui = {};

    for (const [key, fallback] of Object.entries(config.ui)) {
      ui[key] = overrides[key] ?? source.ui?.[key] ?? english.ui?.[key] ?? fallback;
    }

    const featureLabel = overrides[config.featureLabelKey]
      ?? source.ui?.[config.featureLabelKey]
      ?? localeOverrides.en?.[pluginKey]?.[config.featureLabelKey]
      ?? english.ui?.[config.featureLabelKey]
      ?? config.featureLabelKey;

    const featureDescription = localeOverrides[code]?.featureDescriptions?.[pluginKey]
      ?? localeOverrides.en?.featureDescriptions?.[pluginKey]
      ?? config.featureDescription;

    const payload = {
      code,
      feature: {
        label: featureLabel,
        description: featureDescription
      },
      ui
    };

    writeFileSync(join(targetDir, `${code}.json`), `${JSON.stringify(payload, null, 2)}\n`, 'utf8');
  }
}

